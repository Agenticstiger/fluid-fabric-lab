"""The `streaming` add-on tier's proof: the lab's Kafka carries a stream, and its listeners and ACLs hold.

`lab check --tier streaming` runs one Kubernetes Job in namespace `kafka`, in the
pinned Strimzi Kafka image, using that image's own console clients:

  1  N JSON records, each carrying this run's marker, are produced to the open
     topic `lab-check.events` over the `plain` listener (9092, no TLS, no
     authentication: what forge's Spark Kafka source can read) and consumed
     back; exactly those N records must come back.
  2  `lab-check-writer` over the `tls` listener (9093, SCRAM-SHA-512, a certificate
     from the lab CA) writes to `lab-check.restricted`, which has ACLs for it.
     A positive control: without it, 3 could pass because nothing works.
  3  `lab-check-nobody`, the same way, has no ACL there and is refused with a
     topic authorization error (not an authentication failure).
  4  An anonymous client on `plain` is refused a cluster operation (adding an
     ACL: ClusterAuthorizationException) and a read of `lab-check.restricted`
     (TopicAuthorizationException): `allow.everyone.if.no.acl.found` does not
     leave the cluster or an ACL-protected topic open.

The users' passwords are generated by Strimzi into Secrets of namespace `kafka` and
reach the pod only as secretKeyRef environment variables. They are also redacted
from every log line the launcher prints.
"""

from __future__ import annotations

import base64
import json
import re
import secrets as _secrets
import time
from typing import Optional

from labctl import jobs, kube, mirror

NAMESPACE = "kafka"
CLUSTER = "lab-kafka"
KAFKA_IMAGE_ID = "strimzi-kafka"
BOOTSTRAP_PLAIN = f"{CLUSTER}-kafka-bootstrap.{NAMESPACE}.svc:9092"
BOOTSTRAP_TLS = f"{CLUSTER}-kafka-bootstrap.{NAMESPACE}.svc:9093"
WRITER, NOBODY = "lab-check-writer", "lab-check-nobody"
OPEN_TOPIC, RESTRICTED_TOPIC = "lab-check.events", "lab-check.restricted"
RECORDS = 20
KAFKA_UID = 1001       # the Strimzi Kafka image's user (`kafka`), group 0
JOB_DEADLINE_S = 600
READY_TIMEOUT_S = 300
JOB_LABEL, JOB_KIND = jobs.CHECK_LABEL, "streaming"
PROBE = jobs.Probe(namespace=NAMESPACE, selector=f"{JOB_LABEL}={JOB_KIND}", what="streaming check Job",
                   containers=("check",), deadline_s=JOB_DEADLINE_S)
# What `lab up` creates in the kafka release (platform/components/kafka/values.yaml).
READY_TARGETS = (f"kafka/{CLUSTER}", f"kafkatopic/{OPEN_TOPIC}", f"kafkatopic/{RESTRICTED_TOPIC}",
                 f"kafkauser/{WRITER}", f"kafkauser/{NOBODY}")
_MARK = re.compile(r"^(LAB-STREAM-[A-Z]+) (.*)$", re.M)

# Runs in the pod. Bash, no `set -e`: every client's exit code is data. The marks it prints
# are what `judge` reads; the indented lines are the clients' last words, for a human.
SCRIPT = r"""
set -u
umask 077
export LOG_DIR=/work/logs KAFKA_HEAP_OPTS="-Xms32m -Xmx192m"
B=/opt/kafka/bin
mkdir -p "$LOG_DIR"
props() {
  cat > "$3" <<EOF
security.protocol=SASL_SSL
sasl.mechanism=SCRAM-SHA-512
sasl.jaas.config=org.apache.kafka.common.security.scram.ScramLoginModule required username="$1" password="$2";
ssl.truststore.type=PEM
ssl.truststore.location=/etc/lab-ca/ca.crt
request.timeout.ms=15000
delivery.timeout.ms=30000
max.block.ms=30000
EOF
}
START=$($B/kafka-get-offsets.sh --bootstrap-server "$PLAIN" --topic "$OPEN_TOPIC" 2>/work/o.err | head -n 1 | cut -d: -f3)
case "$START" in ''|*[!0-9]*) echo "LAB-STREAM-ERROR no start offset on $OPEN_TOPIC: '$START'"; sed 's/^/  offsets: /' /work/o.err | tail -n 6; exit 1;; esac
i=1
while [ "$i" -le "$N" ]; do printf '{"run":"%s","seq":%s}\n' "$MARKER" "$i"; i=$((i+1)); done > /work/events.jsonl
# enable.idempotence=false: once the cluster resource has an ACL, an anonymous idempotent producer would
# depend on how the authorizer answers "Write on any topic" for a principal with no ACLs; this check does
# not rely on it (docs/streaming-tier.md).
timeout 120 $B/kafka-console-producer.sh --bootstrap-server "$PLAIN" --topic "$OPEN_TOPIC" \
  --producer-property enable.idempotence=false < /work/events.jsonl > /work/p.out 2>&1
prc=$?
printf 'LAB-STREAM-PRODUCED {"marker":"%s","n":%s,"start":%s,"rc":%s}\n' "$MARKER" "$N" "$START" "$prc"
tail -n 4 /work/p.out | sed 's/^/  producer: /'
timeout 120 $B/kafka-console-consumer.sh --bootstrap-server "$PLAIN" --topic "$OPEN_TOPIC" --partition 0 --offset "$START" \
  --max-messages "$N" --timeout-ms 60000 > /work/c.out 2> /work/c.err
crc=$?
printf 'LAB-STREAM-CONSUMED {"rc":%s}\n' "$crc"
tail -n 4 /work/c.err | sed 's/^/  consumer: /'
sed 's/^/LAB-STREAM-RECORD /' /work/c.out
attempt() {
  props "$1" "$2" "/work/$1.properties"
  out=$(printf '{"run":"%s","who":"%s"}\n' "$MARKER" "$1" | timeout 120 $B/kafka-console-producer.sh \
    --bootstrap-server "$TLS" --topic "$RESTRICTED_TOPIC" --producer.config "/work/$1.properties" --sync 2>&1)
  rc=$?
  d=$(printf '%s' "$out" | grep -c -e TopicAuthorizationException -e 'Not authorized to access topics' || true)
  a=$(printf '%s' "$out" | grep -c -e SaslAuthenticationException -e 'Authentication failed' || true)
  printf 'LAB-STREAM-%s {"user":"%s","rc":%s,"denied":%s,"authn":%s}\n' "$3" "$1" "$rc" "$d" "$a"
  printf '%s\n' "$out" | tail -n 6 | sed "s/^/  $1: /"
}
attempt "$WRITER" "$WRITER_PASSWORD" WRITER
attempt "$NOBODY" "$NOBODY_PASSWORD" NOBODY
# Anonymous on `plain` must not reach the cluster or the ACL-protected topic. The ACL it tries to add is
# harmless (an unused principal on an unused topic), should the authorizer ever let it through.
out=$(timeout 60 $B/kafka-acls.sh --bootstrap-server "$PLAIN" --add --allow-principal User:lab-check-never \
  --operation Describe --topic lab-check.acl-probe 2>&1)
rc=$?
d=$(printf '%s' "$out" | grep -c -e ClusterAuthorizationException -e 'Cluster authorization failed' || true)
printf 'LAB-STREAM-ACLDENY {"rc":%s,"denied":%s}\n' "$rc" "$d"
printf '%s\n' "$out" | tail -n 4 | sed 's/^/  anonymous acls: /'
timeout 120 $B/kafka-console-consumer.sh --bootstrap-server "$PLAIN" --topic "$RESTRICTED_TOPIC" --partition 0 --offset 0 \
  --max-messages 1 --timeout-ms 20000 > /work/a.out 2> /work/a.err
rc=$?
d=$(grep -c -e TopicAuthorizationException -e 'Not authorized to access topics' /work/a.err || true)
leaked=$(wc -l < /work/a.out | tr -d ' ')
printf 'LAB-STREAM-ANONREAD {"rc":%s,"denied":%s,"leaked":%s}\n' "$rc" "$d" "$leaked"
tail -n 4 /work/a.err | sed 's/^/  anonymous read: /'
exit 0
"""


class StreamingError(jobs.JobError):
    pass


def kafka_ref(lock: dict) -> str:
    entry = mirror.lock_image(lock, KAFKA_IMAGE_ID)
    return f"{entry['registry']}/{entry['repository']}@{entry['digest']}"


def _password(user: str) -> dict:
    return {"name": f"{user.split('-')[-1].upper()}_PASSWORD",
            "valueFrom": {"secretKeyRef": {"name": user, "key": "password"}}}


def job(name: str, image: str, marker: str) -> dict:
    """The check Job. Pod Security `restricted`; the passwords come from Strimzi's Secrets by env only."""
    return {
        "apiVersion": "batch/v1", "kind": "Job",
        "metadata": {"name": name, "namespace": NAMESPACE,
                     "labels": {"app.kubernetes.io/part-of": "fluid-fabric-lab", JOB_LABEL: JOB_KIND}},
        "spec": {
            "backoffLimit": 0, "activeDeadlineSeconds": JOB_DEADLINE_S, "ttlSecondsAfterFinished": 3600,
            "template": {
                "metadata": {"labels": {JOB_LABEL: JOB_KIND}},
                "spec": {
                    "restartPolicy": "Never", "automountServiceAccountToken": False,
                    "securityContext": {"runAsNonRoot": True, "seccompProfile": {"type": "RuntimeDefault"}},
                    "volumes": [{"name": "work", "emptyDir": {"sizeLimit": "64Mi"}},
                                {"name": "lab-ca", "configMap": {"name": "lab-ca-bundle"}}],
                    "containers": [{
                        "name": "check", "image": image, "imagePullPolicy": "IfNotPresent",
                        "command": ["bash", "-c", SCRIPT],
                        "env": [{"name": "MARKER", "value": marker}, {"name": "N", "value": str(RECORDS)},
                                {"name": "PLAIN", "value": BOOTSTRAP_PLAIN}, {"name": "TLS", "value": BOOTSTRAP_TLS},
                                {"name": "OPEN_TOPIC", "value": OPEN_TOPIC},
                                {"name": "RESTRICTED_TOPIC", "value": RESTRICTED_TOPIC},
                                {"name": "WRITER", "value": WRITER}, {"name": "NOBODY", "value": NOBODY},
                                _password(WRITER), _password(NOBODY)],
                        "securityContext": {"runAsUser": KAFKA_UID, "runAsGroup": 0, "allowPrivilegeEscalation": False,
                                            "capabilities": {"drop": ["ALL"]}},
                        "volumeMounts": [{"name": "work", "mountPath": "/work"},
                                         {"name": "lab-ca", "mountPath": "/etc/lab-ca", "readOnly": True}],
                        "resources": {"requests": {"cpu": "100m", "memory": "256Mi"}, "limits": {"memory": "512Mi"}},
                    }],
                },
            },
        },
    }


def marks(logs: str) -> dict:
    """The LAB-STREAM-* lines the check prints (but RECORD), as {mark: payload}."""
    return {m.group(1): m.group(2).strip() for m in _MARK.finditer(logs or "") if m.group(1) != "LAB-STREAM-RECORD"}


def record_lines(logs: str) -> list:
    """The consumed records, one payload string per LAB-STREAM-RECORD line."""
    return [m.group(2).strip() for m in _MARK.finditer(logs or "") if m.group(1) == "LAB-STREAM-RECORD"]


def _json(found: dict, key: str) -> dict:
    try:
        value = json.loads(found[key])
    except (KeyError, ValueError) as exc:
        raise StreamingError(f"the check did not finish its steps (missing or bad {key})") from exc
    if not isinstance(value, dict):
        raise StreamingError(f"{key} is not a JSON object")
    return value


def _is_int(*values) -> bool:
    """True only for real ints: not True, not 1.0, not "1" (a JSON mark is data, never trusted by shape)."""
    return all(type(v) is int for v in values)


def judge(found: dict, records: list, marker: str) -> dict:
    """The run's result; StreamingError unless all three claims hold."""
    produced, consumed = _json(found, "LAB-STREAM-PRODUCED"), _json(found, "LAB-STREAM-CONSUMED")
    writer, nobody = _json(found, "LAB-STREAM-WRITER"), _json(found, "LAB-STREAM-NOBODY")
    acl, anon = _json(found, "LAB-STREAM-ACLDENY"), _json(found, "LAB-STREAM-ANONREAD")
    if not (_is_int(produced.get("n"), produced.get("rc"), produced.get("start"), consumed.get("rc"))
            and _is_int(writer.get("rc"), writer.get("denied"), writer.get("authn"))
            and _is_int(nobody.get("rc"), nobody.get("denied"), nobody.get("authn"))
            and _is_int(acl.get("rc"), acl.get("denied"))
            and _is_int(anon.get("rc"), anon.get("denied"), anon.get("leaked"))):
        raise StreamingError("a mark carries a count or exit code that is not an integer: "
                             f"{produced} {consumed} {writer} {nobody} {acl} {anon}")
    if produced.get("marker") != marker or produced.get("n") != RECORDS or produced.get("rc") != 0:
        raise StreamingError(f"producing {RECORDS} records to {OPEN_TOPIC} over plain failed: {produced}")
    if consumed.get("rc") != 0:
        raise StreamingError(f"the consumer on plain exited {consumed.get('rc')} before {RECORDS} records arrived")
    seqs = []
    for text in records:
        try:
            row = json.loads(text)
        except ValueError as exc:
            raise StreamingError(f"a consumed record is not JSON: {text[:80]!r}") from exc
        if not isinstance(row, dict) or row.get("run") != marker:
            raise StreamingError(f"a consumed record does not carry this run's marker: {text[:80]!r}")
        seqs.append(row.get("seq"))
    if not _is_int(*seqs) or sorted(seqs) != list(range(1, RECORDS + 1)):
        raise StreamingError(f"consumed seq {seqs}, expected exactly 1..{RECORDS} once each")
    if (writer.get("rc"), writer.get("denied"), writer.get("authn")) != (0, 0, 0):
        raise StreamingError(f"{WRITER} over tls+SCRAM could not write to {RESTRICTED_TOPIC} (the positive "
                             f"control): {writer}")
    if nobody.get("authn"):
        raise StreamingError(f"{NOBODY} failed to authenticate over tls+SCRAM, so its refusal proves nothing: {nobody}")
    if nobody.get("rc") == 0 or not nobody.get("denied"):
        raise StreamingError(f"{NOBODY} was not refused with a topic authorization error on {RESTRICTED_TOPIC}: "
                             f"{nobody}")
    if acl["rc"] == 0 or not acl["denied"]:
        raise StreamingError("an anonymous client on plain was not refused a cluster operation (adding an ACL); "
                             f"is the ACL on the cluster resource missing? {acl}")
    # The console consumer logs a TopicAuthorizationException and exits 0 (seen live on 2026-11-19), so its
    # exit code says nothing here: the refusal is the authorization error, and no record may come out.
    if not anon["denied"] or anon["leaked"]:
        raise StreamingError(f"an anonymous client on plain was not refused a read of {RESTRICTED_TOPIC} with a "
                             f"topic authorization error (records leaked: {anon['leaked']}): {anon}")
    return {"records": len(seqs), "marker": marker, "start_offset": produced.get("start")}


def passwords(k: kube.Kube) -> dict:
    """{user: password} from the Secrets Strimzi's user operator generated; {} for one not there (yet)."""
    out = {}
    for user in (WRITER, NOBODY):
        found = k.get("secret", user, NAMESPACE) or {}
        raw = (found.get("data") or {}).get("password")
        if raw:
            out[user] = base64.b64decode(raw).decode("utf-8", "replace")
    return out


def _redact(text: str, known: dict) -> str:
    """Every user's password removed in the forms a log could show it: raw, base64 of it, and base64 of
    `user:password` (longest first: the last contains the one before when the prefix is a multiple of 3 bytes)."""
    for user, password in known.items():
        if not password:
            continue
        forms = (base64.b64encode(f"{user}:{password}".encode()).decode(), base64.b64encode(password.encode()).decode(),
                 password)
        for form in sorted(forms, key=len, reverse=True):
            text = text.replace(form, "<redacted>")
    return text


def wait_ready(k: kube.Kube) -> None:
    """The Kafka cluster, both topics and both users Ready (the entity operator has made their ACLs and Secrets)."""
    for target in READY_TARGETS:
        try:
            k.wait("condition=Ready", target, NAMESPACE, timeout_s=READY_TIMEOUT_S)
        except kube.KubeError as exc:
            raise StreamingError(f"{target} is not Ready: {exc}",
                                 f"`kubectl -n {NAMESPACE} describe {target}` shows why; `lab up --tier streaming` "
                                 "resumes.") from exc


def run_check(k: kube.Kube, lock: dict, *, clock=time.monotonic, sleep=time.sleep) -> dict:
    """Run the check Job and judge it.

    labctl.jobs runs it: a Job that does not finish (it cannot start, runs out of time, or this run is
    interrupted) is deleted. A finished one stays an hour (ttlSecondsAfterFinished) for its logs.
    """
    wait_ready(k)
    name = f"lab-check-streaming-{int(time.time())}-{_secrets.token_hex(3)}"
    marker = f"lab-check-{_secrets.token_hex(6)}"
    known = passwords(k)
    try:
        done, why, logs = jobs.run(k, PROBE, name, job(name, kafka_ref(lock), marker),
                                   redact=lambda text: _redact(text, known), clock=clock, sleep=sleep)
        if done != "succeeded":
            raise jobs.failure(PROBE, name, done, why, logs, "check")
    except jobs.JobError as exc:
        raise StreamingError(str(exc), exc.advice) from exc
    try:
        return {**judge(marks(logs), record_lines(logs), marker), "job": name}
    except StreamingError as exc:
        tail = " | ".join(line for line in logs.splitlines()[-14:] if line.strip())
        raise StreamingError(f"{exc} (Job {NAMESPACE}/{name}; log tail: {tail[-700:]})",
                             f"`kubectl -n {NAMESPACE} logs job/{name}` shows the whole run.") from exc
